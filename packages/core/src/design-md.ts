import type { Normalized } from './normalize';
import type { RawSnapshot } from './raw';
import { slugify } from './normalize';
import { TRANSLATION_RULES, VERIFY_LOOP } from './guide';

// Front matter follows the common DESIGN.md token layout so existing DESIGN.md tooling can lint it; only source tokens go there.

const TOP_OBSERVED = 12;
const yamlStr = (s: string) => JSON.stringify(s);

interface ScreenRef { id: string; name: string; file: string; outline: string; feature: string | null; pageName: string; status: { value: string }; viewport: { width: number; height: number } }

function colorValue(v: any): string | null {
  return v && typeof v.color === 'string' ? (v.alpha < 1 ? `${v.color}${Math.round(v.alpha * 255).toString(16).padStart(2, '0')}` : v.color) : null;
}

export function designMd(n: Normalized, snap: RawSnapshot, screens: ScreenRef[]): string {
  const colors: [string, string][] = [];
  const rounded: [string, string][] = [];
  const spacing: [string, string][] = [];
  for (const v of n.variables as any[]) {
    const key = slugify(v.name);
    if (v.type === 'COLOR') {
      const c = colorValue(v.resolvedDefault);
      if (c) colors.push([key, c]);
    } else if (v.type === 'FLOAT' && typeof v.resolvedDefault === 'number') {
      if (v.scopes.includes('CORNER_RADIUS') && v.scopes.length === 1) rounded.push([key, `${v.resolvedDefault}px`]);
      else if (v.scopes.includes('GAP') && v.scopes.every((s: string) => s === 'GAP' || s === 'WIDTH_HEIGHT')) spacing.push([key, `${v.resolvedDefault}px`]);
    }
  }
  for (const s of n.styles as any[])
    if (s.type === 'PAINT' && s.paints.length === 1 && s.paints[0].type === 'solid') colors.push([slugify(s.name), s.paints[0].color]);
  const typography = (n.styles as any[]).filter((s) => s.type === 'TEXT');

  const fm: string[] = ['---', `name: ${yamlStr(snap.file.name)}`];
  const section = (title: string, rows: [string, string][]) => {
    if (!rows.length) return;
    fm.push(`${title}:`);
    for (const [k, v] of rows) fm.push(`  ${k}: ${yamlStr(v)}`);
  };
  section('colors', colors);
  if (typography.length) {
    fm.push('typography:');
    for (const t of typography) {
      fm.push(`  ${slugify(t.name)}:`, `    fontFamily: ${yamlStr(t.fontFamily)}`, `    fontSize: ${yamlStr(`${t.fontSize}px`)}`);
      const w = t.inferred?.[0]?.value;
      if (w) fm.push(`    fontWeight: ${w}`);
      if (t.lineHeight.unit !== 'auto') fm.push(`    lineHeight: ${yamlStr(t.lineHeight.unit === 'px' ? `${t.lineHeight.value}px` : `${t.lineHeight.value}%`)}`);
      if (t.letterSpacing.value) fm.push(`    letterSpacing: ${yamlStr(t.letterSpacing.unit === 'px' ? `${t.letterSpacing.value}px` : `${t.letterSpacing.value / 100}em`)}`);
    }
  }
  section('rounded', rounded);
  section('spacing', spacing);
  fm.push('---', '');

  const md: string[] = [
    `# ${snap.file.name} — F2F design spec`,
    '',
    'Generated by F2F from the Figma Plugin API. Do not edit by hand; re-export instead.',
    '',
    '## How to read this package',
    '',
    '- **Start with the screen outline** (screens/<screen>.md): one line per layer with size, screen position, layout, style, text, component and asset. Open the JSON file only for the details the outline leaves out.',
    '- **Source facts** — `geometry`, `layout`, `style`, `text`, `component` on every node in `screens/*.json`. These are values read from Figma. Implement them exactly.',
    '- **Calculated** — `node.calculated` (screen-relative boxes, insets, measured gaps, alignments, overlaps, near-misses). Derived from source geometry; a measured gap is not necessarily a configured Auto Layout gap — prefer `layout.itemSpacing` when the parent uses Auto Layout.',
    '- **Inferred** — `node.inferred` and `inferred` on text styles. Guesses with a stated basis; confirm before relying on them.',
    '- **Unknown / unsupported** — `node.unsupported`, `reports/unresolved-items.json`. Do not invent values for these; ask.',
    '- Units: px for lengths, degrees for rotation, 0–1 for opacity/alpha, `#rrggbb` for colours. Absolute boxes are Figma canvas coordinates; `calculated.screenBox` is relative to the screen frame origin.',
    '- Instances with `childrenOmitted: "identical-to-component-definition"` render exactly like their definition in `components/components.json`; reuse the existing code component.',
    '',
    '## Implementation rules',
    '',
    '1. Inspect the target repository first and reuse its existing components, tokens, and styling system. Never replace an existing component that already matches a Figma component.',
    '2. Use tokens (variables/styles) by name where the design binds them (`style.variables`, `style.styles`), rather than hard-coding their resolved values.',
    '3. Use the real assets listed in `assets/manifest.json`. Never redraw icons with CSS or substitute generated imagery.',
    '4. Treat `flows/navigation.json` as prototype intent only, not production requirements.',
    '5. Responsive behaviour: only rules marked `source` in each screen\'s `responsive` list were defined by the designer. Rules marked `unknown` must be confirmed.',
    '6. Verify the result by measuring rendered geometry against `calculated.screenBox` with `f2f verify`; screenshots in `assets/screenshots/` are references only.',
    '',
    TRANSLATION_RULES,
    VERIFY_LOOP,
    'Tagging: web `data-figma-id="<id>"`; Flutter `Semantics(identifier: "figma:<id>")`; React Native `testID="figma:<id>"`; Compose `Modifier.testTag("figma:<id>")`; SwiftUI `.accessibilityIdentifier("figma:<id>")`. `f2f build --feature <name> --repo .` writes a brief with the exact snippet for your framework.',
    '',
  ];

  md.push('## Tokens', '');
  if (!n.variables.length && !n.styles.length) md.push('_No variables or shared styles were found in the exported scope._', '');
  else {
    md.push(`${n.variables.length} variables in ${n.collections.length} collections and ${n.styles.length} shared styles — full detail including modes and aliases in [tokens/tokens.json](tokens/tokens.json).`, '');
    if (colors.length) md.push('### Colours (source)', '', ...colors.map(([k, v]) => `- \`${k}\`: ${v}`), '');
    if (typography.length)
      md.push('### Text styles (source; weight inferred from style name)', '', ...typography.map((t) => `- \`${slugify(t.name)}\`: ${t.fontFamily} ${t.fontStyle}, ${t.fontSize}px, line-height ${t.lineHeight.unit === 'auto' ? 'auto' : `${t.lineHeight.value}${t.lineHeight.unit === 'px' ? 'px' : '%'}`}, letter-spacing ${t.letterSpacing.value}${t.letterSpacing.unit === 'px' ? 'px' : '%'}`), '');
  }
  md.push('### Observed values (calculated usage counts across exported screens)', '');
  md.push('Colours: ' + (n.usage.colors.slice(0, TOP_OBSERVED).map((c) => `${c.color} ×${c.count}`).join(', ') || 'none'), '');
  md.push('Type (family|style|size|line-height|letter-spacing): ' + (n.usage.typography.slice(0, TOP_OBSERVED).map((t) => `\`${t.key}\` ×${t.count}`).join(', ') || 'none'), '');

  md.push('## Components', '');
  if (!n.components.length) md.push('_No component instances in the exported scope._', '');
  for (const c of n.components as any[]) {
    const variant = c.variant ? ` — variant ${Object.entries(c.variant).map(([k, v]) => `${k}=${v}`).join(', ')}` : '';
    md.push(`- **${c.name}** (\`${c.id}\`)${variant}${c.remote ? ' — library component' : ''}${c.definition ? '' : ' — definition unavailable'}`);
  }
  md.push('');

  md.push('## Screens', '');
  for (const s of screens)
    md.push(`- [${s.name}](${s.outline}) ([full JSON](${s.file})) — ${s.feature ?? s.pageName}, ${s.viewport.width}×${s.viewport.height}, status: ${s.status.value}`);
  md.push('', '## Reports', '', '- [Extraction report](reports/extraction-report.json) — counts, skipped layers, errors, unsupported properties.', '- [Unresolved items](reports/unresolved-items.json) — decisions that need a human.', '');
  return fm.join('\n') + '\n' + md.join('\n');
}
